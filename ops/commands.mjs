// Every oh command, once: what it is called, what it takes, what it
// needs, where its how-to is, an example, and the function that does it.
// The help (oh help) and the reference (docs/reference/oh.md, written by
// `./oh help --markdown`) are both made from this table, and
// ops/oh.test.mjs fails when the reference and the table differ.

const lazy = (module, name) => async (ctx, said) => (await import(module))[name](ctx, said);

const CF = ['CLOUDFLARE_API_TOKEN', 'CLOUDFLARE_ACCOUNT_ID'];

/// What an argument is, said once for every command that takes it.
export const ARGUMENTS = {
  account: 'an account (32 hex characters) or one of its devices\' keys (64 hex characters)',
  query: 'a name the account plays under (or had taken off), or the email address its web subscription was paid with',
  what: '`name`, `picture`, or `name,picture`',
  row: '`app` (remote config), `service` (service settings) or `relay` (relay settings)',
  file: 'a JSON file holding the whole row',
  name: 'a secret\'s name, as `infra/cloudflare.mjs` lists it',
  platform: '`ios` or `android`',
  document: '`terms` (the terms of use) or `privacy` (the privacy policy)',
};

