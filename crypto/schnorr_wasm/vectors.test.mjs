for (const [i, [sk, pk, aux, msg, sig]] of vectors.entries()) {
  test(`vector ${i}: signed bit for bit, verified, and a flipped bit refused`, () => {
    put('sk', sk);
    put('aux', aux);
    put('msg', msg);
    assert.equal(sign(at.sk, at.msg, at.aux, at.sig), 1);
    assert.equal(read('sig', 64), sig);
    put('pk', pk);
    assert.equal(verify(at.pk, at.msg, at.sig), 1);
    const flipped = Buffer.from(sig, 'hex');
    flipped[63] ^= 1;
    put('sig', flipped.toString('hex'));
    assert.equal(verify(at.pk, at.msg, at.sig), 0);
  });
}
